/// The world a script plugin is built against (see [`world`]).
pub(super) const WORLD: &str = "rekindle-build";

/// The interfaces a plugin with this manifest imports: the always-available
/// ones, plus one per requested capability (implied ones included, so a
/// `read-messages` plugin can call `users`).
fn imports(m: &Manifest) -> Vec<&'static str> {
    let mut ifaces = vec!["host", "host-events", "settings"];
    for cap in Capability::ALL {
        if let Some(i) = cap.interface().filter(|_| m.requests(cap)) {
            ifaces.push(i);
        }
    }
    if m.requests(Capability::ReadClient) {
        ifaces.push("inspect");
    }
    if m.requests(Capability::Compose) {
        ifaces.push("compose-control");
    }
    if m.requests(Capability::Ui) {
        ifaces.push("elements");
    }
    ifaces
}

/// The hook exports a plugin with this manifest gets: lifecycle, events, UI
/// and timers always; `compose-handler`, `renderer` and
/// `notification-filter` only with their capability, so the component itself
/// says what it hooks.
pub(super) fn exports(m: &Manifest) -> Vec<&'static str> {
    crate::runtime::HOOKS
        .into_iter()
        .filter(|h| crate::runtime::hook_capability(h).is_none_or(|c| m.requests(c)))
        .collect()
}

/// A world (in the rekindle package) that imports `host` and only the
/// interfaces the manifest's capabilities cover, and exports the hooks it
/// may implement.
///
/// The Rust build gets the same effect by dropping unused imports; these
/// toolchains import every interface their world names, so the world itself
/// is cut down. A plugin importing an interface it didn't request fails the
/// build (see [`explain_failure`]).
fn world(m: &Manifest) -> String {
    let items: Vec<String> = imports(m)
        .iter()
        .map(|i| format!("    import {i};"))
        .chain(exports(m).iter().map(|e| format!("    export {e};")))
        .collect();
    format!(
        "/// Generated by `rekindle build` for `{}`.\nworld {WORLD} {{\n{}\n}}\n",
        m.id,
        items.join("\n")
    )
}

/// Write the rekindle WIT package plus the generated world into `dir`.
fn write_wit(dir: &Path, m: &Manifest) -> Result<()> {
    std::fs::create_dir_all(dir)?;
    for (name, text) in WIT_FILES {
        std::fs::write(dir.join(name), text)?;
    }
    std::fs::write(dir.join("build.wit"), world(m))?;
    Ok(())
}

/// A build's scratch directory under `<target>/rekindle/`, holding the world
/// in `wit/`; removed when dropped. Each build gets its own, so concurrent
/// builds of one project (two test binaries) don't collide.
pub(super) struct BuildDir(PathBuf);

impl BuildDir {
    pub(super) fn new(target_dir: &Path, m: &Manifest) -> Result<Self> {
        use std::sync::atomic::{AtomicU64, Ordering};
        static SEQ: AtomicU64 = AtomicU64::new(0);
        let name = format!(
            "build-{}-{}",
            std::process::id(),
            SEQ.fetch_add(1, Ordering::Relaxed)
        );
        let dir = target_dir.join("rekindle").join(name);
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(dir.join("wit"))
            .with_context(|| format!("creating {}", dir.display()))?;
        write_wit(&dir.join("wit"), m)?;
        // Absolute, so generated imports can be made relative to it.
        Ok(Self(absolute(&dir)?))
    }

    pub(super) fn path(&self) -> &Path {
        &self.0
    }

    pub(super) fn wit(&self) -> PathBuf {
        self.0.join("wit")
    }
}

impl Drop for BuildDir {
    fn drop(&mut self) {
        // A scratch directory left behind is harmless, and the next build
        // uses another name.
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

/// Absolute, without Windows' verbatim prefix (which node mishandles).
pub fn absolute(p: &Path) -> Result<PathBuf> {
    if !p.exists() {
        bail!("{} doesn't exist", p.display());
    }
    Ok(super::dunce(p))
}

/// Run a toolchain step, capturing its output (returned on success). Their
/// output is noisy (bundler diagnostics, progress lines), so it's shown only
/// on failure.
pub(super) fn run(mut cmd: Command, what: &str, m: &Manifest) -> Result<String> {
    let out = cmd.output().with_context(|| format!("running {what}"))?;
    let text = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    if out.status.success() {
        return Ok(text);
    }
    if let Some(why) = explain_failure(&text, m) {
        bail!("{why}");
    }
    bail!("{what} failed:\n{}", tail(&tidy(&text), 60));
}

/// A toolchain's failure output with its own machinery taken out: terminal
/// colors, stack frames inside node and jco, JS error-object dumps, the
/// wrapper's own error (the cause follows `Caused by:`), and paths relative
/// to the build directory rather than the project.
fn tidy(output: &str) -> String {
    let mut s = strip_ansi(output);
    if let Some(i) = s.rfind("Caused by:") {
        s = s[i + "Caused by:".len()..].to_string();
    }
    for wrapper in [
        "(jco componentizeCommand) ",
        "[Error: : Failed to evaluate user JavaScript module: Failed to finish JavaScript module evaluation: ",
        "[Error: : Failed to evaluate user JavaScript module: Failed to declare JavaScript module: ",
    ] {
        s = s.replace(wrapper, "");
    }
    // Generated-file paths: the build dir is three levels under the project
    // (`target/rekindle/build-*`).
    s = s.replace("../../../", "");
    let noise = |l: &str| {
        let t = l.trim();
        (t.starts_with("at ")
            && (t.contains("node_modules")
                || t.contains("file:///")
                || t.contains("/entry.mjs")
                || t.contains("<anonymous>")))
            || matches!(
                t,
                "}" | "] {" | "errors: [Getter/Setter]" | "code: 'GenericFailure'"
            )
    };
    let kept: Vec<&str> = s.lines().filter(|l| !noise(l)).collect();
    kept.join("\n").trim().to_string()
}

fn strip_ansi(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\u{1b}' && chars.peek() == Some(&'[') {
            chars.next();
            for c in chars.by_ref() {
                if c.is_ascii_alphabetic() {
                    break;
                }
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// Whether `e` is [`explain_failure`]'s "doesn't request" error.
pub(super) fn is_missing_capability(e: &anyhow::Error) -> bool {
    format!("{e:#}").contains("but its manifest doesn't request")
}

/// The capabilities `interfaces` need that `m` doesn't request, each once,
/// in the order of [`Capability::ALL`].
pub(super) fn missing_for_interfaces<'a>(
    interfaces: impl Iterator<Item = &'a str>,
    m: &Manifest,
) -> Vec<Capability> {
    let mut missing: Vec<Capability> = interfaces
        .filter_map(Capability::for_interface)
        .filter(|c| !m.requests(*c))
        .collect();
    missing.sort_by_key(|c| Capability::ALL.iter().position(|a| a == c));
    missing.dedup();
    missing
}

/// Recognise the failures that have a rekindle-specific fix.
fn explain_failure(output: &str, m: &Manifest) -> Option<String> {
    // The entry module's own checks (templates/js/entry.mjs) already say
    // what's wrong; drop the toolchain's wrapping around them.
    for marker in [
        "is not a rekindle handler",
        "which the manifest doesn't request, so the client",
        "but handlers must be",
    ] {
        let clean = strip_ansi(output);
        if let Some(line) = clean.lines().find(|l| l.contains(marker)) {
            let at = line.find(marker).unwrap_or(0);
            let start = line[..at]
                .rfind("Error: ")
                .map_or(0, |i| i + "Error: ".len());
            return Some(
                line[start..]
                    .trim()
                    .trim_end_matches(['\'', '"', ']', ')'])
                    .to_string(),
            );
        }
    }
    // An import of an interface outside the world: the bundler can't
    // resolve `rekindle:plugin/theming@…`.
    for iface in after_all(output, "rekindle:plugin/", |c| {
        c.is_ascii_lowercase() || c == '-'
    }) {
        if let Some(cap) = Capability::for_interface(&iface).filter(|c| !m.requests(*c)) {
            return Some(format!(
                "the plugin imports the `{iface}` interface but its manifest doesn't request `{cap}`; add it to `capabilities`"
            ));
        }
    }
    // A JS module that threw while loading: this engine reports only that
    // the entry's export never came to be, not what was thrown.
    if output.contains("exported variable 'lifecycle' does not exist")
        || output.contains("exported variable 'guest' does not exist")
    {
        return Some(
            "the plugin's module threw while loading. Top-level code runs during `rekindle build`, and the engine doesn't \
             report what it threw here: look for top-level code that can fail, or move it into `activate`, where an error \
             is reported with its stack"
                .into(),
        );
    }
    // A rekindle API called at the top level of the module, which runs at
    // build time, when there is no host to call: jco reports the import as
    // undefined.
    let called = output
        .match_indices("unknown import: `")
        .find_map(|(i, m)| {
            let rest = output[i + m.len()..].strip_prefix("rekindle:plugin/")?;
            let (iface, rest) = rest.split_once('@')?;
            let func: String = rest
                .split_once('#')?
                .1
                .chars()
                .take_while(|&c| c.is_ascii_lowercase() || c == '-')
                .collect();
            Some(format!("{iface}.{func}"))
        });
    if let Some(call) = called {
        return Some(format!(
            "the plugin calls `{call}` at the top level of its module. Top-level code runs during `rekindle build` \
             (the result is snapshotted into the plugin), when there is no client to call; make the call in `activate`"
        ));
    }
    None
}

/// The names a component imports (its top-level import section).
pub(super) fn component_imports(component: &[u8]) -> Result<Vec<String>> {
    use wasmparser::{Parser, Payload};
    let mut depth = 0usize;
    let mut names = Vec::new();
    for payload in Parser::new(0).parse_all(component) {
        match payload.context("malformed component")? {
            Payload::Version { .. } => depth += 1,
            Payload::End(_) => depth = depth.saturating_sub(1),
            Payload::ComponentImportSection(s) if depth == 1 => {
                for import in s {
                    names.push(
                        import
                            .context("malformed component import")?
                            .name
                            .full_name()
                            .into_owned(),
                    );
                }
            }
            _ => {}
        }
    }
    Ok(names)
}

/// Each identifier that follows `prefix` in `text`.
fn after_all<'a>(
    text: &'a str,
    prefix: &'a str,
    ident: impl Fn(char) -> bool + Copy + 'a,
) -> impl Iterator<Item = String> + 'a {
    text.match_indices(prefix)
        .map(move |(i, _)| {
            text[i + prefix.len()..]
                .chars()
                .take_while(|&c| ident(c))
                .collect::<String>()
        })
        .filter(|s| !s.is_empty())
}

fn tail(text: &str, lines: usize) -> String {
    let all: Vec<&str> = text.lines().collect();
    all[all.len().saturating_sub(lines)..].join("\n")
}

/// `path` relative to `from`, with `/` separators (for an `import` in a
/// generated module). Both must be absolute.
pub(super) fn relative_import(from: &Path, path: &Path) -> String {
    let from: Vec<_> = from.components().collect();
    let to: Vec<_> = path.components().collect();
    let common = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut parts: Vec<String> = vec!["..".into(); from.len() - common];
    parts.extend(
        to[common..]
            .iter()
            .map(|c| c.as_os_str().to_string_lossy().into_owned()),
    );
    let joined = parts.join("/");
    if joined.starts_with("..") {
        joined
    } else {
        format!("./{joined}")
    }
}

/// The first `rel` that exists under `dir` or one of its ancestors (a
/// monorepo's hoisted `node_modules`).
pub fn find_up(dir: &Path, rel: &[&str]) -> Option<PathBuf> {
    dir.ancestors()
        .flat_map(|d| rel.iter().map(move |r| d.join(r)))
        .find(|p| p.exists())
}

/// Validate script metadata the same way `[package.metadata.rekindle]` is.
pub(super) fn manifest_from(
    meta: &ScriptMeta,
    project_dir: &Path,
    pkg_name: &str,
    version: &str,
    description: &str,
    authors: &[String],
) -> Result<Manifest> {
    let mut m = manifest::CargoMetadata {
        id: meta.id.clone(),
        name: meta.name.clone(),
        capabilities: meta.capabilities.clone(),
        network: meta.network.clone(),
        settings: meta.settings.clone(),
        compose_uploads: meta.compose_uploads,
        updates: meta.updates.clone(),
    }
    .into_manifest(pkg_name, version, description, authors)?;
    m.strings = manifest::load_strings(project_dir)?;
    m.validate()?;
    Ok(m)
}

/// The `rekindle` table of a `package.json`: the Cargo fields, plus where
/// the code starts.
#[derive(Debug, Clone, serde::Deserialize)]
#[serde(deny_unknown_fields, rename_all = "kebab-case")]
pub(super) struct ScriptMeta {
    id: String,
    name: Option<String>,
    #[serde(default)]
    capabilities: Vec<String>,
    #[serde(default)]
    network: Vec<String>,
    /// The settings schema (design doc §10).
    #[serde(default)]
    settings: Option<serde_json::Value>,
    #[serde(default)]
    compose_uploads: bool,
    /// Where the author publishes updates (see `manifest::UpdateSource`).
    #[serde(default)]
    updates: Option<manifest::UpdateSource>,
    /// The entry file (default `src/index.ts`, then `.js`).
    pub(super) entry: Option<String>,
    /// `quickjs` (default) or `starlingmonkey`.
    pub(super) engine: Option<String>,
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use super::*;

    fn manifest(caps: &[Capability]) -> Manifest {
        Manifest {
            schema: manifest::SCHEMA,
            id: "dev.test.x".into(),
            name: "X".into(),
            version: "0.1.0".into(),
            description: String::new(),
            authors: vec![],
            capabilities: caps.to_vec(),
            network: if caps.contains(&Capability::Network) {
                vec!["api.example.com".into()]
            } else {
                vec![]
            },
            wit: manifest::rekindle_wit_version().into(),
            settings: vec![],
            strings: BTreeMap::default(),
            compose_uploads: false,
            updates: None,
            theme: false,
        }
    }

    fn world_block(w: &str) -> &str {
        &w[w.find(&format!("world {WORLD}")).unwrap()..]
    }

    #[test]
    fn world_imports_host_and_only_requested_interfaces() {
        let w = world(&manifest(&[
            Capability::Storage,
            Capability::Compose,
            Capability::Network,
            Capability::ReadMessages,
        ]));
        let block = world_block(&w);
        for present in [
            "host",
            "host-events",
            "settings",
            "storage",
            "http",
            "messages",
            "users",
        ] {
            assert!(block.contains(&format!("import {present};")), "{present}");
        }
        assert!(block.contains("export lifecycle;") && block.contains("export compose-handler;"));
        assert!(!block.contains("export renderer;"), "no render-messages");
        // `compose` gates an export, not an import.
        for absent in ["ui", "theming", "overlay", "clipboard", "client-state"] {
            assert!(!block.contains(&format!("import {absent};")), "{absent}");
        }
        let bare = world(&manifest(&[]));
        assert_eq!(world_block(&bare).matches("import ").count(), 3);
        assert_eq!(world_block(&bare).matches("export ").count(), 4);
    }

    #[test]
    fn explains_an_unrequested_interface() {
        let m = manifest(&[Capability::Storage]);
        let js = "Error resolving module 'rekindle:plugin/theming@0.10.0' from '/entry.js'";
        assert!(
            explain_failure(js, &m)
                .unwrap()
                .contains("doesn't request `theming`")
        );
    }

    #[test]
    fn explains_a_top_level_call() {
        let m = manifest(&[Capability::Storage]);
        let js = "Error: ... 0x50425 - <unknown>!<wasm function 389>: unknown import: `rekindle:plugin/host@0.10.0#log` has not been defined] {";
        assert!(
            explain_failure(js, &m)
                .unwrap()
                .contains("calls `host.log` at the top level")
        );
        // A requested interface isn't the problem.
        assert!(explain_failure("rekindle:plugin/storage@0.10.0 something else", &m).is_none());
        assert!(explain_failure("SyntaxError: unexpected token", &m).is_none());
    }

    #[test]
    fn relative_imports() {
        let from = Path::new("/p/target/rekindle/build");
        assert_eq!(
            relative_import(from, Path::new("/p/src/index.ts")),
            "../../../src/index.ts"
        );
        assert_eq!(
            relative_import(Path::new("/p"), Path::new("/p/src/a.js")),
            "./src/a.js"
        );
    }
}
