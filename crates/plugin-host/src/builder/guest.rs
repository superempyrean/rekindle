//! What a script-language build (TypeScript) needs beyond the Rust one: the
//! WIT world it's built against, finding and running its toolchain, and
//! turning the toolchain's failure into something that names the fix.
//!
//! jco embeds an interpreter in the component and pre-initializes it at
//! build time (the plugin's top-level code runs during `rekindle build` and
//! is snapshotted). It runs with every WASI import stubbed out, so the
//! component imports only `rekindle:plugin` interfaces. The host checks that
//! again at load, as it does for every plugin.

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

use crate::capability::Capability;
use crate::manifest::{self, Manifest};

