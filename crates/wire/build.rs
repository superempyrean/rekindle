//! Generates the `PropId` tables from `propid-names.tsv`.
//!
//! The TSV is the recovered id->name table read out of Phoenix's Android host
//! library (`liblibdiscord_wasm_host.so`, build 356207, VA 0x5d9fcf0, reached
//! through the GOT entry at 0x617e0d8). It is the source of truth. This
//! script turns it into two arrays that mirror the two tables the binary
//! carries:
//!
//! - `NAMES`: a dense id -> &str array indexed by the numeric id (the host's
//!   id->name table at VA 0x5d9fcf0).
//! - `SORTED`: a name-sorted (&str, u16) array that `PropId::from_name` binary
//!   searches (the host's name->id table at VA 0x5da3260).

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn main() {
    let tsv = "propid-names.tsv";
    println!("cargo:rerun-if-changed={tsv}");

    let text = fs::read_to_string(tsv).expect("read propid-names.tsv");
    let mut names: Vec<Option<String>> = Vec::new();
    for line in text.lines() {
        let line = line.trim_end_matches(['\r', '\n']);
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (id, name) = line
            .split_once('\t')
            .unwrap_or_else(|| panic!("no tab in {line:?}"));
        let id: usize = id.parse().unwrap_or_else(|_| panic!("bad id in {line:?}"));
        if id >= names.len() {
            names.resize(id + 1, None);
        }
        assert!(names[id].is_none(), "duplicate id {id}");
        names[id] = Some(name.to_string());
    }

    // The ids must be 0..N contiguous: the binary indexes the array directly.
    let count = names.len();
    let names: Vec<String> = names
        .into_iter()
        .enumerate()
        .map(|(i, n)| n.unwrap_or_else(|| panic!("id {i} missing (ids must be contiguous)")))
        .collect();

    // name -> id, sorted lexicographically like the host's name->id table.
    let mut sorted: BTreeMap<&str, u16> = BTreeMap::new();
    for (id, name) in names.iter().enumerate() {
        assert!(
            sorted.insert(name, id as u16).is_none(),
            "duplicate name {name:?}"
        );
    }

    let mut out = String::new();
    writeln!(
        out,
        "// @generated by build.rs from propid-names.tsv. Do not edit."
    )
    .unwrap();
    writeln!(out, "pub(crate) const COUNT: usize = {count};").unwrap();

    write!(out, "pub(crate) static NAMES: [&str; {count}] = [").unwrap();
    for name in &names {
        write!(out, "{name:?},").unwrap();
    }
    writeln!(out, "];").unwrap();

    write!(out, "pub(crate) static SORTED: [(&str, u16); {count}] = [").unwrap();
    for (name, id) in &sorted {
        write!(out, "({name:?},{id}),").unwrap();
    }
    writeln!(out, "];").unwrap();

    let dest = Path::new(&env::var("OUT_DIR").unwrap()).join("prop_id_table.rs");
    fs::write(dest, out).expect("write prop_id_table.rs");
}
