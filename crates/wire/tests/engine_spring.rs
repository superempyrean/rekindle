#[test]
fn the_spring_matches_the_engine_frame_by_frame() {
    for c in CASES {
        let f = |i: usize| f32::from_bits(c.spec[i]);
        let to = f(0);
        let mut run = SpringRun::start(
            c.from,
            to,
            Spring {
                mass: f(1),
                stiffness: f(2),
                damping: f(3),
            },
            c.spec[4],
            f(5),
            f(6),
            f(7),
            0.0,
        );
        assert_eq!(f32::from_bits(c.values[0]), c.from, "{}", c.name);
        let scale = (to - c.from).abs().max(1.0);
        for (k, (dt, want)) in c.dt.iter().zip(&c.values[1..]).enumerate() {
            let want = f32::from_bits(*want);
            let got = run.step(*dt).value;
            if want == to {
                // A settled spring lands on its target exactly.
                assert!(
                    got == to || (got - to).abs() < 1e-4 * scale,
                    "{} frame {k}: {got} vs {want}",
                    c.name
                );
            } else {
                assert!(
                    (got - want).abs() <= 1e-4 * scale,
                    "{} frame {k}: {got} vs {want}",
                    c.name
                );
            }
        }
    }
}

#[test]
fn the_engine_settles_on_the_same_frame() {
    for c in CASES {
        let f = |i: usize| f32::from_bits(c.spec[i]);
        let to = f(0);
        let mut run = SpringRun::start(
            c.from,
            to,
            Spring {
                mass: f(1),
                stiffness: f(2),
                damping: f(3),
            },
            c.spec[4],
            f(5),
            f(6),
            f(7),
            0.0,
        );
        let engine = c.values[1..].iter().position(|v| {
            f32::from_bits(*v) == to
                && c.values[1..]
                    .iter()
                    .skip_while(|w| f32::from_bits(**w) != to)
                    .all(|w| f32::from_bits(*w) == to)
        });
        let ours = c.dt.iter().position(|dt| run.step(*dt).settled);
        assert_eq!(ours, engine, "{}", c.name);
    }
}
